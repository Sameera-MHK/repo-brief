import path from 'node:path';

const MAX_TREE_LINES = 150;
const MAX_TREE_DEPTH = 4;

const FENCE_LANGUAGES = {
  '.js': 'js', '.mjs': 'js', '.cjs': 'js', '.jsx': 'jsx', '.ts': 'ts', '.tsx': 'tsx', '.json': 'json',
  '.md': 'markdown', '.py': 'python', '.rb': 'ruby', '.go': 'go', '.rs': 'rust', '.java': 'java',
  '.sh': 'bash', '.yml': 'yaml', '.yaml': 'yaml', '.html': 'html', '.css': 'css', '.scss': 'scss',
  '.vue': 'vue', '.svelte': 'svelte', '.sql': 'sql', '.toml': 'toml', '.php': 'php', '.cs': 'csharp',
};

/** Rough token estimate: about 4 characters per token for English text and code. */
export const estimateTokens = (chars) => Math.ceil(chars / 4);

function buildTree(paths) {
  const root = {};
  for (const p of paths) {
    let node = root;
    for (const part of p.split('/')) node = node[part] ??= {};
  }
  return root;
}

function countFiles(node) {
  const keys = Object.keys(node);
  return keys.length === 0 ? 1 : keys.reduce((sum, k) => sum + countFiles(node[k]), 0);
}

export function renderTree(paths) {
  const lines = ['.'];
  let truncated = false;
  const walk = (node, prefix, depth) => {
    const keys = Object.keys(node).sort((a, b) => {
      const aDir = Object.keys(node[a]).length > 0;
      const bDir = Object.keys(node[b]).length > 0;
      if (aDir !== bDir) return aDir ? -1 : 1;
      return a < b ? -1 : a > b ? 1 : 0;
    });
    keys.forEach((key, i) => {
      if (lines.length >= MAX_TREE_LINES) {
        truncated = true;
        return;
      }
      const last = i === keys.length - 1;
      const child = node[key];
      const isDir = Object.keys(child).length > 0;
      const branch = last ? '└── ' : '├── ';
      if (isDir && depth >= MAX_TREE_DEPTH) {
        lines.push(`${prefix}${branch}${key}/ (${countFiles(child)} files)`);
      } else {
        lines.push(`${prefix}${branch}${key}${isDir ? '/' : ''}`);
        if (isDir) walk(child, prefix + (last ? '    ' : '│   '), depth + 1);
      }
    });
  };
  walk(buildTree(paths), '', 1);
  if (truncated) lines.push(`... (tree truncated at ${MAX_TREE_LINES} lines)`);
  return lines.join('\n');
}

function fenceFor(content) {
  let fence = '```';
  while (content.includes(fence)) fence += '`';
  return fence;
}

function excludedSummary(excluded) {
  const counts = {};
  for (const item of excluded) counts[item.reason] = (counts[item.reason] || 0) + 1;
  return Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

export function renderMarkdown({ analysis, scan, selected, omitted }) {
  const a = analysis;
  const out = [];
  const push = (...lines) => out.push(...lines);

  push(`# Repository Brief: ${a.name}`, '');
  push('> Generated by RepoBrief. Read this brief first, then inspect the original source files before making changes.', '');

  push('## Project Overview', '');
  if (a.description) push(`**Description (package.json):** ${a.description}`, '');
  const meta = [a.version && `version ${a.version}`, a.license && `license ${a.license}`].filter(Boolean);
  if (meta.length) push(`**Package:** \`${a.name}\` (${meta.join(', ')})`, '');
  if (a.readmeSummary) push(`**From ${a.readmePath}:** ${a.readmeSummary}`, '');
  const topLevel = [...new Set(scan.files.filter((f) => f.path.includes('/')).map((f) => f.path.split('/')[0]))].sort();
  if (topLevel.length) push(`**Top-level directories:** ${topLevel.map((d) => `\`${d}/\``).join(', ')}`, '');
  push(`**Files:** ${scan.totalFiles} found, ${scan.files.length} eligible, ${scan.excluded.length} excluded, ${selected.length} included below.`, '');

  push('## Technology Stack', '');
  if (a.languages.length) push(`- **Languages (by file extension):** ${a.languages.map((l) => `${l.name} (${l.files})`).join(', ')}`);
  if (a.frameworks.length) push(`- **Frameworks:** ${a.frameworks.map((f) => `${f.name} (${f.evidence})`).join(', ')}`);
  if (a.buildTools.length) push(`- **Build tools:** ${a.buildTools.map((t) => `${t.name} (${t.evidence})`).join(', ')}`);
  if (a.testTools.length) push(`- **Testing:** ${a.testTools.map((t) => `${t.name} (${t.evidence})`).join(', ')}`);
  if (a.dependencies.length) push(`- **Dependencies:** ${a.dependencies.map((d) => `\`${d}\``).join(', ')}`);
  if (a.devDependencies.length) push(`- **Dev dependencies:** ${a.devDependencies.map((d) => `\`${d}\``).join(', ')}`);
  if (!a.frameworks.length) push('- No framework detected from repository configuration.');
  push('');

  push('## Directory Structure', '', '```text', renderTree(scan.files.map((f) => f.path)), '```', '');

  push('## Architecture and Entry Points', '');
  push('**Confirmed** (declared in configuration):', '');
  if (a.entryPoints.confirmed.length) for (const e of a.entryPoints.confirmed) push(`- \`${e.path}\` — ${e.evidence}`);
  else push('- None declared.');
  push('', '**Inferred** (from file names and locations; verify before relying on them):', '');
  if (a.entryPoints.inferred.length) for (const e of a.entryPoints.inferred) push(`- \`${e.path}\` — ${e.evidence}`);
  if (a.routes.length) for (const r of a.routes) push(`- \`${r}\` — possible route or API handler (path naming)`);
  if (!a.entryPoints.inferred.length && !a.routes.length) push('- None inferred.');
  push('');

  push('## Development Commands', '');
  const scripts = Object.entries(a.scripts);
  if (scripts.length) {
    push('From `package.json` scripts:', '');
    for (const [name, cmd] of scripts) push(`- \`npm run ${name}\` — \`${cmd}\``);
  } else {
    push('No package.json scripts found.');
  }
  push('');

  push('## Important Files', '');
  if (selected.length) for (const f of selected) push(`- \`${f.path}\` — ${f.reason}`);
  else push('No files were selected.');
  push('');

  push('## Coding Conventions', '');
  if (a.conventions.length) for (const c of a.conventions) push(`- ${c}`);
  else push('No conventions could be confirmed from configuration or source files.');
  push('');

  push('## Source Context', '');
  for (const f of selected) {
    const fence = fenceFor(f.content);
    const lang = FENCE_LANGUAGES[path.extname(f.path).toLowerCase()] || '';
    push(`### ${f.path}`, '', `${fence}${lang}`, f.content.replace(/\n$/, ''), fence, '');
  }
  if (omitted.length) {
    push('### Omitted Files', '', 'The size limit was reached, so these eligible files were not included:', '');
    for (const f of omitted) push(`- \`${f.path}\` (${f.reason})`);
    push('');
  }
  const summary = excludedSummary(scan.excluded);
  if (summary.length) {
    push('### Excluded Files', '', 'Files excluded by safety or ignore rules (contents never read into this brief):', '');
    for (const [reason, count] of summary) push(`- ${reason}: ${count}`);
    push('');
  }

  push('## AI Assistant Instructions', '');
  push(
    '- Read this repository brief before making changes.',
    '- Inspect the original source files before making assumptions; this brief may be incomplete.',
    '- Follow the existing project conventions.',
    '- Avoid unrelated changes.',
    '- Ask before destructive operations.',
    '- Explain important implementation decisions.',
  );
  return out.join('\n') + '\n';
}

export function renderJson({ analysis, scan, selected, omitted }) {
  const data = {
    generator: 'repobrief',
    project: analysis,
    stats: {
      totalFiles: scan.totalFiles,
      eligibleFiles: scan.files.length,
      excludedFiles: scan.excluded.length,
      selectedFiles: selected.length,
      omittedFiles: omitted.length,
    },
    structure: scan.files.map((f) => f.path),
    files: selected.map((f) => ({ path: f.path, reason: f.reason, content: f.content })),
    omitted,
    excluded: excludedSummary(scan.excluded).map(([reason, count]) => ({ reason, count })),
  };
  return JSON.stringify(data, null, 2) + '\n';
}
